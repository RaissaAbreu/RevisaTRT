// Assinatura de release: o CI (GitHub Actions) fornece a chave por variáveis de ambiente.
// Sem elas, o build de release usa a chave de debug (útil só para testes locais).
val keystorePath: String? = System.getenv("REVISATRT_KEYSTORE")

android {
    namespace = "app.revisatrt"
    compileSdk = 35

    defaultConfig {
        applicationId = "app.revisatrt"
        minSdk = 26
        targetSdk = 35
        versionCode = (System.getenv("REVISATRT_VERSION_CODE") ?: "1").toInt()
        versionName = System.getenv("REVISATRT_VERSION_NAME") ?: "1.0"
    }

    signingConfigs {
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("REVISATRT_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("REVISATRT_KEY_ALIAS")
                keyPassword = System.getenv("REVISATRT_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = if (keystorePath != null) signingConfigs.getByName("release")
            else signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    sourceSets {
        // esquemas do banco para o teste de migração (só no build de debug)
        getByName("debug").assets.srcDir("$projectDir/schemas")
    }
    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all {
                it.systemProperty("roborazzi.test.record", "true")
                it.systemProperty("roborazzi.outputDir", "${rootDir}/capturas")
            }
        }
    }
}

